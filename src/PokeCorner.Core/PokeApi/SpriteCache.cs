using System.Reflection;
using System.Text.Json;

namespace PokeCorner.Core.PokeApi;

public sealed class SpriteCache
{
    private readonly string _cacheDirectory;
    private IReadOnlyList<Domain.SpeciesEvolutionChain>? _cachedOfflineStarters;

    public SpriteCache(string cacheDirectory)
    {
        _cacheDirectory = cacheDirectory;
        Directory.CreateDirectory(_cacheDirectory);
    }

    public async Task<byte[]?> GetOrFetchAsync(int speciesId, Func<Task<byte[]>> fetch)
    {
        var path = Path.Combine(_cacheDirectory, $"{speciesId}.png");
        var cached = await TryReadAsync(path);
        if (cached is not null)
        {
            if (IsCompletePng(cached)) return cached;
            DeleteQuietly(path); // cut short mid-write — re-download below instead of crashing every decoder
        }

        byte[] bytes;
        try
        {
            bytes = await fetch();
        }
        catch (Exception ex) when (ex is HttpRequestException or TaskCanceledException)
        {
            // Fresh offline first launch (or a network blip): degrade gracefully instead of
            // crashing the caller. There's nothing to cache, so leave the disk untouched.
            return null;
        }

        if (!IsCompletePng(bytes))
        {
            // Empty body, an HTML error page, a truncated download: treat it like a failed fetch.
            // Caching it would hand every caller bytes their image decoder throws on.
            return null;
        }

        // Temp file + move, so a reader polling this path never opens a half-written file. A
        // write that loses a race with another writer still returns the bytes it fetched.
        try
        {
            var tempPath = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
            await File.WriteAllBytesAsync(tempPath, bytes);
            try { File.Move(tempPath, path, overwrite: true); }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { DeleteQuietly(tempPath); }
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { }
        return bytes;
    }

    /// null when the file is missing or can't be read right now (another thread is writing it).
    private static async Task<byte[]?> TryReadAsync(string path)
    {
        if (!File.Exists(path)) return null;
        try { return await File.ReadAllBytesAsync(path); }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { return null; }
    }

    /// Synchronous, network-free peek at the on-disk sprite cache, for UI-thread thumbnails.
    /// null when the species isn't cached (yet), the file is mid-write, or it is truncated —
    /// callers show a placeholder rather than block.
    public byte[]? TryGetCachedBytes(int speciesId)
    {
        var path = Path.Combine(_cacheDirectory, $"{speciesId}.png");
        if (!File.Exists(path)) return null;
        byte[] cached;
        try { cached = File.ReadAllBytes(path); }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { return null; } // mid-write: not cached yet
        if (IsCompletePng(cached)) return cached;
        DeleteQuietly(path); // the next GetOrFetchAsync re-downloads it
        return null;
    }

    private static readonly byte[] PngSignature = { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A };
    private static readonly byte[] PngIendTrailer = { 0, 0, 0, 0, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82 };

    /// Signature at the front, IEND chunk at the very end. Every decoder in the App (overlay,
    /// Pokédex thumbnails, catch reveal, starter picker) throws on a file that fails this, and a
    /// write interrupted by a crash or power loss is exactly what loses the trailing IEND.
    /// Not full validation — a complete file with corrupt chunks in the middle still passes.
    private static bool IsCompletePng(byte[] bytes) =>
        bytes.AsSpan().StartsWith(PngSignature) && bytes.AsSpan().EndsWith(PngIendTrailer);

    private static void DeleteQuietly(string path)
    {
        try { File.Delete(path); }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { }
    }

    /// The bundled, network-independent species catalog: every Gen 1-5 evolution chain (species
    /// 1-649), generated by crawling PokeAPI with the same logic as
    /// SpeciesCatalog.RefreshFromNetworkAsync, so its ids, names and chain shapes are PokeAPI's
    /// own. Backs first-run starter selection and every offline catch.
    public IReadOnlyList<Domain.SpeciesEvolutionChain> LoadOfflineStarters()
    {
        if (_cachedOfflineStarters is not null)
        {
            return _cachedOfflineStarters;
        }

        var assembly = Assembly.GetExecutingAssembly();
        using var stream = assembly.GetManifestResourceStream("PokeCorner.Core.PokeApi.OfflineStarterFallback.json")
            ?? throw new InvalidOperationException("OfflineStarterFallback.json embedded resource not found.");
        var starters = JsonSerializer.Deserialize<List<Domain.SpeciesEvolutionChain>>(stream)!;
        _cachedOfflineStarters = starters;
        return starters;
    }
}
